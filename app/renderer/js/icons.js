export function icon(name, size = 16, extra = '') {
  return `<svg class="i ${extra}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths[name] ?? ''}</svg>`;
}

/** Replaces every <i data-icon="name" data-size="16"> in the page with its SVG. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('i[data-icon]'))
    el.outerHTML = icon(el.dataset.icon, +(el.dataset.size || 16), el.className);
}
